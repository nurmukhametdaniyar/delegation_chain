/// Which instantiation a test or an assertion is compiled for (D-84).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Inst {
    Both,
    Default,
    Aggregate,
}

/// The instantiation a `#[cfg]` line selects, if it is one of the suite's.
fn cfg_of(line: &str) -> Option<Inst> {
    match line.trim() {
        "#[cfg(feature = \"aggregate-variant\")]" => Some(Inst::Aggregate),
        "#[cfg(not(feature = \"aggregate-variant\"))]" => Some(Inst::Default),
        _ => None,
    }
}

/// The argument text of each `assert!`, `assert_eq!` or `assert_ne!` in
/// `body`, whitespace-collapsed, in order, with the instantiation a `#[cfg]`
/// on the line before it selects. String literals are skipped when matching
/// parentheses.
fn assertions(body: &str) -> Vec<(String, Inst)> {
    let b = body.as_bytes();
    let mut out = vec![];
    let mut i = 0;
    while let Some(off) = body[i..].find("assert") {
        let at = i + off;
        let rest = &body[at..];
        let open = ["assert!(", "assert_eq!(", "assert_ne!("]
            .iter()
            .find(|m| rest.starts_with(**m))
            .map(|m| at + m.len());
        let Some(start) = open else {
            i = at + 6;
            continue;
        };
        let (mut depth, mut k, mut instr) = (1, start, false);
        while k < b.len() && depth > 0 {
            let c = b[k];
            if instr {
                if c == b'\\' {
                    k += 1;
                } else if c == b'"' {
                    instr = false;
                }
            } else if c == b'"' {
                instr = true;
            } else if c == b'(' {
                depth += 1;
            } else if c == b')' {
                depth -= 1;
            }
            k += 1;
        }
        let line_start = body[..at].rfind('\n').unwrap_or(0);
        let prev_start = body[..line_start].rfind('\n').map_or(0, |x| x + 1);
        let inst = cfg_of(&body[prev_start..line_start]).unwrap_or(Inst::Both);
        out.push((
            body[start..k - 1]
                .split_whitespace()
                .collect::<Vec<_>>()
                .join(" "),
            inst,
        ));
        i = k;
    }
    out
}

fn counter(field: &str) -> Option<&'static str> {
    Some(match field.trim().trim_start_matches("n.") {
        "pairings()" => "pairings",
        "resolver_calls" => "resolver calls",
        "policy_store_calls" => "policy-store calls",
        "sig_verifications" => "signature checks",
        "hash_to_curve" => "hash-to-G2",
        "miller_loops" => "Miller loops",
        "final_exps" => "final exps",
        _ => return None,
    })
}

/// What one assertion asserts, in the table's words.
fn classify(a: &str) -> Result<String, String> {
    if let Some(i) = a.find("RegistryError::") {
        let name: String = a[i + 15..]
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric())
            .collect();
        return Ok(format!("registry rejects ({name})"));
    }
    if let Some(i) = a.find("Reject::L") {
        let line: String = a[i + 9..]
            .chars()
            .take_while(|c| c.is_ascii_digit())
            .collect();
        return Ok(format!("L{line}"));
    }
    if a.contains("Ok(Decision::AllowWithApproval") {
        return Ok("accept (with approval)".into());
    }
    if a.starts_with("run(") && a.ends_with("Ok(())") {
        return Ok("phase 8 accepts the unmutated chain".into());
    }
    if a.ends_with(".is_ok()") {
        return Ok("accept".into());
    }
    // Operation counts: (n.a, n.b, …), (x, y, …)
    if let Some(rest) = a.strip_prefix('(')
        && let Some((fields, values)) = rest.split_once("), (")
    {
        let values = values.split(')').next().unwrap_or("");
        let f: Vec<&str> = fields
            .split(',')
            .map(str::trim)
            .filter(|x| !x.is_empty())
            .collect();
        let v: Vec<&str> = values.split(',').map(str::trim).collect();
        if f.len() == v.len() && f.iter().all(|x| counter(x).is_some()) {
            return Ok(f
                .iter()
                .zip(&v)
                .map(|(f, v)| format!("{} {v}", counter(f).expect("checked")))
                .collect::<Vec<_>>()
                .join(", "));
        }
    }
    Ok(match a {
        "n.resolver_calls > 0 && n.policy_store_calls > 0" => {
            "cold: resolver and policy-store calls > 0".into()
        }
        "other.load(Relaxed), 0" => "no outcome other than accept, L17, L50".into(),
        a if a.starts_with("per_round.iter().all(|a| *a == 1)") => {
            "exactly 1 accept per round".into()
        }
        "l17.load(Relaxed) + l50.load(Relaxed), ((THREADS - 1) * rounds) as u64" => {
            "every other attempt L17 or L50".into()
        }
        _ => return Err(format!("unclassified assertion: {a}")),
    })
}

/// "L02, L02, L05" → "L02 (×2); L05".
fn compress(v: &[String]) -> String {
    let mut out: Vec<(String, usize)> = vec![];
    for x in v {
        match out.last_mut() {
            Some((y, k)) if y == x => *k += 1,
            _ => out.push((x.clone(), 1)),
        }
    }
    out.into_iter()
        .map(|(x, k)| if k > 1 { format!("{x} (×{k})") } else { x })
        .collect::<Vec<_>>()
        .join("; ")
}

/// One test: its section, name, the instantiations it is compiled for, and
/// its asserted outcomes.
struct TestRow {
    section: String,
    name: String,
    inst: Inst,
    asserted: String,
}

/// Every `#[test]` in `src`, in file order. Sections are the
/// `// ====…==== title` lines; a `#[cfg]` just before `#[test]` limits the
/// test to one instantiation.
fn tests_of(src: &str, default_section: &str) -> Result<Vec<TestRow>, String> {
    let mut out = vec![];
    let mut section = default_section.to_owned();
    let lines: Vec<&str> = src.lines().collect();
    let mut i = 0;
    while i < lines.len() {
        let l = lines[i];
        if let Some(t) = l.strip_prefix("// ====") {
            section = t.trim_start_matches('=').trim().to_owned();
        }
        if l.trim() == "#[test]" {
            let sig = lines.get(i + 1).copied().unwrap_or("");
            let name = sig
                .trim()
                .strip_prefix("fn ")
                .and_then(|s| s.split('(').next())
                .ok_or_else(|| format!("no fn after #[test] at line {}", i + 1))?
                .to_owned();
            // The body runs to the next top-level closing brace.
            let mut j = i + 2;
            while j < lines.len() && lines[j] != "}" {
                j += 1;
            }
            let body = lines[i + 1..=j.min(lines.len() - 1)].join("\n");
            let asserted: Vec<String> = assertions(&body)
                .iter()
                .map(|(a, inst)| {
                    let c = classify(a).map_err(|e| format!("{name}: {e}"))?;
                    Ok(match inst {
                        Inst::Both => c,
                        Inst::Default => format!("default: {c}"),
                        Inst::Aggregate => format!("aggregate variant: {c}"),
                    })
                })
                .collect::<Result<_, String>>()?;
            if asserted.is_empty() {
                return Err(format!("{name}: no assertion found"));
            }
            let inst = i
                .checked_sub(1)
                .and_then(|k| cfg_of(lines[k]))
                .unwrap_or(Inst::Both);
            out.push(TestRow {
                section: section.clone(),
                name,
                inst,
                asserted: compress(&asserted),
            });
            i = j;
        }
        i += 1;
    }
    Ok(out)
}

/// Runs the two suites in release mode, for the default instantiation or,
/// with `aggregate`, the aggregate variant, and returns each test's result.
fn run_suites(root: &Path, aggregate: bool) -> Result<BTreeMap<String, bool>, String> {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let mut cmd = Command::new(cargo);
    cmd.current_dir(root).args([
        "test",
        "--release",
        "-p",
        "delegationchain",
        "--test",
        "security",
        "--test",
        "concurrency",
    ]);
    if aggregate {
        cmd.args(["--features", "aggregate-variant"]);
    }
    let out = cmd.output().map_err(|e| format!("cargo test: {e}"))?;
    let text = String::from_utf8_lossy(&out.stdout);
    let mut m = BTreeMap::new();
    for l in text.lines() {
        if let Some(rest) = l.strip_prefix("test ")
            && let Some((name, res)) = rest.rsplit_once(" ... ")
        {
            m.insert(name.trim().to_owned(), res.trim() == "ok");
        }
    }
    if m.is_empty() {
        return Err(format!(
            "cargo test printed no results:\n{}",
            String::from_utf8_lossy(&out.stderr)
        ));
    }
    Ok(m)
}

/// The security suite as threat → asserted line (SPEC §11.2), for both
/// instantiations (D-84).
fn security(root: &Path) -> Result<String, String> {
    let read = |p: &str| fs::read_to_string(root.join(p)).map_err(|e| format!("{p}: {e}"));
    let mut rows = tests_of(&read("tests/security.rs")?, "security")?;
    rows.extend(tests_of(
        &read("tests/concurrency.rs")?,
        "T3b replay, concurrent (Theorem 5)",
    )?);
    let runs = [run_suites(root, false)?, run_suites(root, true)?];
    let mut w = String::from(HEADER);
    w.push_str("% The security suite (SPEC §11.2): each test's assertions in order, from tests/security.rs and\n% tests/concurrency.rs. Ln is the Algorithm line whose Reject variant the test asserts.\n% The last two columns are the results of running the suites when this file was generated, for the\n% default instantiation (Ed25519 per hop) and the aggregate variant (BLS); --- marks a test compiled\n% for the other instantiation only (D-84).\n");
    w.push_str(
        "\\begin{longtable}{>{\\raggedright\\arraybackslash}p{0.33\\linewidth}>{\\raggedright\\arraybackslash}p{0.42\\linewidth}ll}\n\\toprule\n",
    );
    w.push_str(
        "Test & Asserted, in order & Default & Aggregate \\\\\n\\midrule\n\\endhead\n\\bottomrule\n\\endfoot\n",
    );
    let mut section = String::new();
    let mut passed = [0usize; 2];
    let mut total = [0usize; 2];
    for r in &rows {
        if r.section != section {
            if !section.is_empty() {
                w.push_str("\\midrule\n");
            }
            let _ = writeln!(
                w,
                "\\multicolumn{{4}}{{l}}{{\\emph{{{}}}}} \\\\",
                tex(&r.section)?
            );
            section = r.section.clone();
        }
        let mut cells = vec![];
        for (k, inst) in [Inst::Default, Inst::Aggregate].iter().enumerate() {
            if r.inst != Inst::Both && r.inst != *inst {
                cells.push("---".to_owned());
                continue;
            }
            let ok = *runs[k]
                .get(r.name.as_str())
                .ok_or_else(|| format!("{} did not run ({inst:?})", r.name))?;
            total[k] += 1;
            passed[k] += usize::from(ok);
            cells.push(if ok {
                "yes".into()
            } else {
                "\\textbf{no}".into()
            });
        }
        let _ = writeln!(
            w,
            "\\texttt{{{}}} & {} & {} \\\\",
            // Long test names may break after an underscore.
            tex(&r.name)?.replace("\\_", "\\_\\allowbreak{}"),
            tex(&r.asserted)?,
            cells.join(" & ")
        );
    }
    w.push_str("\\end{longtable}\n");
    let _ = writeln!(
        w,
        "% Default: {} of {} tests passed. Aggregate variant: {} of {} tests passed.",
        passed[0], total[0], passed[1], total[1]
    );
    Ok(w)
}

// ---- the M4 oracle ----

fn oracle(root: &Path) -> Result<String, String> {
    let p = root.join("docs/test-reports/policy-oracle-m4.json");
    let v: Value =
        serde_json::from_str(&fs::read_to_string(&p).map_err(|e| format!("{}: {e}", p.display()))?)
            .map_err(|e| e.to_string())?;
    let n = |v: &Value| -> Result<u64, String> {
        v.as_u64().ok_or_else(|| format!("not a count: {v}"))
    };
    let frac = |v: &Value| -> String { v.as_f64().map_or("---".into(), |x| format!("{x:.4}")) };
    let thousands = |x: u64| -> String {
        let s = x.to_string();
        let mut out = String::new();
        for (i, c) in s.chars().enumerate() {
            if i > 0 && (s.len() - i).is_multiple_of(3) {
                out.push(',');
            }
            out.push(c);
        }
        out
    };
    let c = &v["contains"];
    let mut w = String::from(HEADER);
    let _ = writeln!(
        w,
        "% The M4 differential oracle (SPEC §9.7; seed {}): test statistics, not benchmark results.\n% Soundness: the procedure never answers true where the enumerating oracle answers false.\n% Completeness: the share of the oracle's true answers that the procedure also finds.",
        v["seed"]
    );
    w.push_str("\\begin{tabular}{llrrrr}\n\\toprule\n");
    w.push_str("Procedure & Inputs & Cases & Soundness violations & Oracle true & Completeness \\\\\n\\midrule\n");
    let _ = writeln!(
        w,
        "Contains & all well-formed pairs & {} & {} & {} & {} \\\\",
        thousands(n(&c["wellformed_pairs"])?),
        n(&c["soundness_violations"])?,
        thousands(n(&c["completeness_overall"]["oracle_true"])?),
        frac(&c["completeness_overall"]["completeness"])
    );
    let _ = writeln!(
        w,
        " & no child rule unsatisfiable & & & {} & {} \\\\",
        thousands(n(
            &c["completeness_when_no_child_rule_is_unsatisfiable"]["oracle_true"]
        )?),
        frac(&c["completeness_when_no_child_rule_is_unsatisfiable"]["completeness"])
    );
    if let Some(m) = c["completeness_by_category"].as_object() {
        for (cat, x) in m {
            let _ = writeln!(
                w,
                " & {} & & & {} & {} \\\\",
                tex(cat)?,
                thousands(n(&x["oracle_true"])?),
                frac(&x["completeness"])
            );
        }
    }
    let _ = writeln!(
        w,
        "\\midrule\n\\multicolumn{{6}}{{l}}{{\\emph{{Contains reflexivity: {} checks, {} failures; malformed scopes rejected: {}}}}} \\\\",
        thousands(n(&c["reflexivity_checks"])?),
        n(&c["reflexivity_failures"])?,
        thousands(n(&c["malformed_scopes_rejected"])?)
    );
    w.push_str("\\midrule\n");
    if let Some(m) = v["implies_unsat_by_type"].as_object() {
        for which in ["implies", "unsat"] {
            for (ty, x) in m {
                let _ = writeln!(
                    w,
                    "{} & {} & {} & {} & {} & {} \\\\",
                    if which == "implies" {
                        "Implies"
                    } else {
                        "Unsat"
                    },
                    tex(ty)?,
                    thousands(n(&x["cases"])?),
                    n(&x["soundness_violations"])?,
                    thousands(n(&x[which]["oracle_true"])?),
                    frac(&x[which]["completeness"])
                );
            }
        }
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

/// Writes every table into `out/tables/` and every figure into
/// `out/figures/`.
pub fn render(
    results: &Path,
    criterion: &Path,
    root: &Path,
    out: &Path,
    threads: usize,
) -> Result<(), String> {
    let doc = Doc::load(results, criterion, threads)?;
    // The claims table cites the paper in docs/; its section map must be for
    // that file (D-86).
    let pdf = fs::read(root.join("docs/paper.pdf")).map_err(|e| format!("docs/paper.pdf: {e}"))?;
    let have = crate::report::hex(&dc_types::digest::sha256(&[&pdf]));
    let want = doc
        .sections
        .as_ref()
        .and_then(|m| m["current"]["sha256"].as_str())
        .ok_or("docs/paper-sections.json has no current.sha256")?;
    if have != want {
        return Err(format!(
            "docs/paper-sections.json is for another paper (current.sha256 {want}, docs/paper.pdf {have}): update it from the new paper (D-86)"
        ));
    }
    let tables = out.join("tables");
    fs::create_dir_all(&tables).map_err(|e| e.to_string())?;
    let template = root.join("crates/dc-bench/BENCHMARKS.template.md");
    for (name, body) in [
        ("verdicts.tex", verdicts(&doc)?),
        ("breakeven.tex", breakeven(&doc)?),
        ("claims.tex", claims(&doc, &template)?),
        ("primitives.tex", primitives(&doc)?),
        ("positioning.tex", positioning(&doc)?),
        ("captions.tex", captions()?),
        ("oracle.tex", oracle(root)?),
        ("security.tex", security(root)?),
    ] {
        fs::write(tables.join(name), body).map_err(|e| e.to_string())?;
        eprintln!("paper: tables/{name}");
    }
    let st = Command::new("bash")
        .arg(root.join("scripts/paper_figures.sh"))
        .arg(results)
        .arg(out.join("figures"))
        .status()
        .map_err(|e| format!("figures: {e}"))?;
    if !st.success() {
        return Err(format!("figures failed: {st}"));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn markup_and_specials_are_escaped() {
        assert_eq!(
            tex("**Not supported** in `tests/a_b.rs`: 5% × 2 µs").unwrap(),
            "\\textbf{Not supported} in \\texttt{tests/a\\_b.rs}: 5\\% $\\times$ 2 \\textmu{}s"
        );
        assert_eq!(tex("\"a\" > b").unwrap(), "``a'' $>$ b");
        assert!(tex("ж").is_err());
        assert!(tex("**open").is_err());
    }

    #[test]
    fn assertions_are_classified() {
        let body = r#"
            assert_eq!(v.verify(&x), Err(Reject::L23Unresolvable { k: 2 }));
            assert!(v.verify(&c).is_ok());
            assert_eq!((n.pairings(), n.resolver_calls), (0, 0), "{n:?}");
            assert!(matches!(v.verify(&x), Err(Reject::L02Decode(_))));
        "#;
        let got: Vec<String> = assertions(body)
            .iter()
            .map(|(a, _)| classify(a).unwrap())
            .collect();
        assert_eq!(
            got,
            ["L23", "accept", "pairings 0, resolver calls 0", "L02"]
        );
        assert!(classify("something_else()").is_err());
        // A #[cfg] on the line before an assertion selects an instantiation.
        let body = "    #[cfg(feature = \"aggregate-variant\")]\n    assert!(r.is_ok());\n    assert!(q.is_ok());";
        let insts: Vec<Inst> = assertions(body).iter().map(|x| x.1).collect();
        assert_eq!(insts, [Inst::Aggregate, Inst::Both]);
        assert_eq!(
            compress(&["L02".into(), "L02".into(), "L05".into()]),
            "L02 (×2); L05"
        );
    }
}
