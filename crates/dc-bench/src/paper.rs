/// LaTeX for a cell of `BENCHMARKS.md`: `**bold**` and `` `code` `` become
/// `\textbf` and `\texttt`, and every special character is escaped. A
/// character with no mapping here is an error, so nothing is dropped
/// silently.
pub fn tex(s: &str) -> Result<String, String> {
    let mut out = String::with_capacity(s.len() + 16);
    let (mut bold, mut code, mut quoted) = (false, false, false);
    let mut it = s.chars().peekable();
    while let Some(c) = it.next() {
        if c == '*' && it.peek() == Some(&'*') && !code {
            it.next();
            out.push_str(if bold { "}" } else { "\\textbf{" });
            bold = !bold;
            continue;
        }
        if c == '`' {
            out.push_str(if code { "}" } else { "\\texttt{" });
            code = !code;
            continue;
        }
        if c == '"' {
            out.push_str(if quoted { "''" } else { "``" });
            quoted = !quoted;
            continue;
        }
        out.push_str(&match c {
            '\\' => "\\textbackslash{}".into(),
            '<' => "$<$".into(),
            '>' => "$>$".into(),
            '|' => "$|$".into(),
            '&' => "\\&".into(),
            '%' => "\\%".into(),
            '$' => "\\$".into(),
            '#' => "\\#".into(),
            '_' => "\\_".into(),
            '{' => "\\{".into(),
            '}' => "\\}".into(),
            '~' => "\\textasciitilde{}".into(),
            '^' => "\\textasciicircum{}".into(),
            '×' => "$\\times$".into(),
            '–' => "--".into(),
            '—' => "---".into(),
            'µ' => "\\textmu{}".into(),
            '≈' => "$\\approx$".into(),
            '≥' => "$\\geq$".into(),
            '≤' => "$\\leq$".into(),
            '≠' => "$\\neq$".into(),
            '²' => "\\textsuperscript{2}".into(),
            'α' => "$\\alpha$".into(),
            'β' => "$\\beta$".into(),
            'σ' => "$\\sigma$".into(),
            '±' => "$\\pm$".into(),
            '→' => "$\\rightarrow$".into(),
            '−' => "$-$".into(),
            '§' => "\\S{}".into(),
            '†' => "\\dag{}".into(),
            '’' => "'".into(),
            '“' => "``".into(),
            '”' => "''".into(),
            c if c.is_ascii() => c.to_string(),
            c => return Err(format!("no LaTeX mapping for {c:?} in {s:?}")),
        });
    }
    if bold || code || quoted {
        return Err(format!("unbalanced markup in {s:?}"));
    }
    Ok(out)
}

const HEADER: &str = "% Generated by `dc-bench paper` (crates/dc-bench/src/paper.rs). Do not edit:\n% regenerate it (ARTIFACT.md). Needs booktabs and array (security.tex also longtable).\n";

fn short(v: &str) -> Result<&'static str, String> {
    Ok(match v {
        "net benefit" => "+",
        "not a net benefit" => "$-$",
        "no material difference" => "$=$",
        "inconclusive" => "?",
        "inconclusive (runs disagree)" => "?r",
        _ => return Err(format!("unknown verdict {v}")),
    })
}

/// The §1 verdict table: B/D (warm+prefix), A/C and A/C-batch (warm), each
/// ratio with its 95% CI and its verdict under the frozen rule.
fn verdicts(doc: &Doc) -> Result<String, String> {
    let mut w = String::from(HEADER);
    w.push_str("% The frozen plan's §1 verdict table: median ratio [95% CI] and verdict per cell.\n% Verdicts (frozen plan §6): + net benefit (CI below 0.90); $-$ not a net benefit (CI above 1.10);\n% $=$ no material difference; ? inconclusive; ?r inconclusive because the three runs disagree.\n");
    w.push_str("\\begin{tabular}{lrr@{\\,}cr@{\\,}cr@{\\,}c}\n\\toprule\n");
    w.push_str("Profile & $N$ & \\multicolumn{2}{c}{B/D, warm+prefix} & \\multicolumn{2}{c}{A/C, warm} & \\multicolumn{2}{c}{A/C-batch, warm} \\\\\n\\midrule\n");
    let mut order = cells();
    let rank = |p: &str| {
        ["small", "medium", "large", "medium-approval"]
            .iter()
            .position(|x| *x == p)
    };
    order.sort_by_key(|&(n, p)| (rank(p), n));
    let mut last = "";
    for (n, profile) in order {
        if !last.is_empty() && last != profile {
            w.push_str("\\midrule\n");
        }
        last = profile;
        let mut row = format!("{} & {n}", tex(profile)?);
        for k in ["bd", "ac", "acb"] {
            let (r, _, v) = doc.verdict(k, n, profile)?;
            let _ = write!(
                row,
                " & {:.2} [{:.2}, {:.2}] & {}",
                r.value,
                r.ci.0,
                r.ci.1,
                short(v)?
            );
        }
        let _ = writeln!(w, "{row} \\\\");
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

/// Q2: the break-even N per profile, with the size difference at N = 1 and
/// A's saving over C at N = 10.
fn breakeven(doc: &Doc) -> Result<String, String> {
    let mut w = String::from(HEADER);
    w.push_str("% Q2: chain bytes, A against C. Break-even is the first N in 1-10 at which A's and C's sizes change order.\n");
    w.push_str("\\begin{tabular}{lrrr}\n\\toprule\n");
    w.push_str("Profile & Break-even $N$ & A $-$ C at $N = 1$ (bytes) & A smaller than C at $N = 10$ \\\\\n\\midrule\n");
    for profile in ["small", "medium", "large", "medium-approval"] {
        let be = doc
            .break_even(profile)?
            .map_or("none in 1--10".to_owned(), |n| n.to_string());
        let d1 = doc.total("A", 1, profile)? - doc.total("C", 1, profile)?;
        let s10 = 100.0 * (1.0 - doc.total("A", 10, profile)? / doc.total("C", 10, profile)?);
        let _ = writeln!(w, "{} & {be} & {d1:+.0} & {s10:.1}\\% \\\\", tex(profile)?);
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

/// The claims table: `BENCHMARKS.md`'s §5 table, rendered from the same
/// template and converted.
fn claims(doc: &Doc, template: &Path) -> Result<String, String> {
    let md = doc.fill_for(
        &fs::read_to_string(template).map_err(|e| format!("{}: {e}", template.display()))?,
        Revision::Current,
    )?;
    let start = md
        .find("\n## 5. Paper claims checked")
        .ok_or("BENCHMARKS template has no §5 claims table")?;
    let rows: Vec<Vec<String>> = md[start..]
        .lines()
        .skip_while(|l| !l.starts_with('|'))
        .take_while(|l| l.starts_with('|'))
        .skip(2)
        .map(|l| {
            l.trim()
                .trim_matches('|')
                .split(" | ")
                .map(|c| c.trim().to_owned())
                .collect()
        })
        .collect();
    let mut w = String::from(HEADER);
    w.push_str(
        "% The paper claims checked against revision 2026-09-29 (SPEC §13.11): BENCHMARKS.md §5.\n",
    );
    w.push_str(
        "\\begin{tabular}{>{\\raggedright\\arraybackslash}p{0.27\\linewidth}l>{\\raggedright\\arraybackslash}p{0.11\\linewidth}>{\\raggedright\\arraybackslash}p{0.42\\linewidth}}\n\\toprule\n",
    );
    w.push_str("Claim & Paper & Verdict & Evidence \\\\\n\\midrule\n");
    for (i, r) in rows.iter().enumerate() {
        if r.len() != 4 {
            return Err(format!("claims row {} has {} cells", i + 1, r.len()));
        }
        let cells: Vec<String> = r.iter().map(|c| tex(c)).collect::<Result<_, _>>()?;
        let _ = writeln!(w, "{} \\\\", cells.join(" & "));
        if i + 1 < rows.len() {
            w.push_str("\\addlinespace\n");
        }
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

/// Microseconds for the primitives table: like the report's, with three
/// decimals below one microsecond.
fn prim_us(ns: f64) -> String {
    if ns < 1000.0 {
        format!("{:.3}", ns / 1000.0)
    } else {
        us(ns)
    }
}

/// Primitive costs: criterion medians and their 95% CIs (D-73).
fn primitives(doc: &Doc) -> Result<String, String> {
    let get = |id: &str| -> Result<(f64, (f64, f64)), String> {
        doc.criterion
            .iter()
            .find(|c| c.0 == id)
            .map(|c| (c.1, c.2))
            .ok_or_else(|| format!("no criterion estimate {id}"))
    };
    let mut w = String::from(HEADER);
    w.push_str(
        "% Primitive costs on this machine: criterion medians, 95% CIs, microseconds (D-73).\n",
    );
    w.push_str("\\begin{tabular}{lrr}\n\\toprule\n");
    w.push_str("Operation & Median (\\textmu{}s) & 95\\% CI (\\textmu{}s) \\\\\n\\midrule\n");
    let line = |w: &mut String, label: &str, id: &str| -> Result<(), String> {
        let (m, ci) = get(id)?;
        let _ = writeln!(
            w,
            "{} & {} & [{}, {}] \\\\",
            tex(label)?,
            prim_us(m),
            prim_us(ci.0),
            prim_us(ci.1)
        );
        Ok(())
    };
    w.push_str("\\multicolumn{3}{l}{\\emph{BLS12-381 (blst)}} \\\\\n");
    line(&mut w, "verify (one signature)", "bls/verify")?;
    for n in 2..=11 {
        line(
            &mut w,
            &format!("`aggregate_verify`, {n} messages"),
            &format!("bls/aggregate_verify/{n}"),
        )?;
    }
    line(&mut w, "Miller loop", "bls/miller_loop")?;
    line(&mut w, "final exponentiation", "bls/final_exp")?;
    line(
        &mut w,
        "hash-to-G2 proxy: context + `aggregate`",
        "bls/hash_to_g2_proxy",
    )?;
    line(&mut w, "pairing context alone", "bls/pairing_context")?;
    let h = get("bls/hash_to_g2_proxy")?.0 - get("bls/pairing_context")?.0;
    let _ = writeln!(
        w,
        "{} & {} & --- \\\\",
        tex("hash to G2, estimated (proxy − context)")?,
        prim_us(h)
    );
    w.push_str("\\midrule\n\\multicolumn{3}{l}{\\emph{Ed25519 (ed25519-dalek)}} \\\\\n");
    line(
        &mut w,
        "`verify_strict` (one signature)",
        "ed25519/verify_strict",
    )?;
    for n in 2..=11 {
        line(
            &mut w,
            &format!("`verify_batch`, {n} signatures"),
            &format!("ed25519/verify_batch/{n}"),
        )?;
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

/// Exploratory: C (warm) and D (warm+prefix) against arm E, medium, at
/// matching depth. Its caption, which lists E's functional gaps, is
/// `\\tabcapPositioning` in `paper/tables/captions.tex`.
fn positioning(doc: &Doc) -> Result<String, String> {
    let mut w = String::from(HEADER);
    w.push_str("% EXPLORATORY (not pre-registered): BENCHMARKS.md §8. Caption: \\tabcapPositioning (paper/tables/captions.tex).\n");
    w.push_str("\\begin{tabular}{lrrrrrr}\n\\toprule\n");
    w.push_str("$N$ (Biscuit depth) & C, warm (\\textmu{}s) & D, warm+prefix (\\textmu{}s) & E (\\textmu{}s) & AIP's code here (\\textmu{}s; exploratory) & C $\\div$ E & D $\\div$ E \\\\\n\\midrule\n");
    for r in doc.positioning()? {
        let _ = writeln!(
            w,
            "{} ({}) & {} & {} & {} & {} & {:.2} & {:.2} \\\\",
            r.n,
            r.n - 1,
            us(r.c),
            us(r.d),
            us(r.e),
            r.aip.map_or("---".into(), us),
            r.c / r.e,
            r.d / r.e
        );
    }
    w.push_str("\\bottomrule\n\\end{tabular}\n");
    Ok(w)
}

